export function statusOfMini(s, serverReady) {
  if (!s?.connected) return { text: "متصل نیست", color: "#9ca3af" };
  if (!s.enabled) return { text: "خاموش", color: "#fbbf24" };
  if (s.lastError) return { text: "خطا", color: "#f87171" };
  if (!serverReady) return { text: "سرور آماده نیست", color: "#f87171" };
  return { text: "فعال", color: "#34d399" };
}

